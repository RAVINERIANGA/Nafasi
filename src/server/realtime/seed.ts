const minute = 60_000;

function ago(ms: number) {
  return new Date(Date.now() - ms).toISOString();
}

function actor(id: string): ActorStamp {
  const user = users.find((item) => item.id === id)!;
  const facility = facilities.find((item) => item.id === user.facilityId)!;
  return {
    id: user.id,
    name: user.name,
    role: user.role,
    subrole: user.subrole,
    registrationNumber: user.registrationNumber,
    facilityId: user.facilityId,
    facilityName: facility.name,
  };
}

function event(
  partial: Omit<
    AuditEvent,
    "id" | "deviceId" | "deviceLabel" | "registrationNumber" | "actorName" | "actorRole" | "facilityName" | "actorId" | "facilityId"
  > & { actor: ActorStamp },
): AuditEvent {
  return {
    id: `evt_${crypto.randomUUID()}`,
    deviceId: "seed-device",
    deviceLabel: "Seeded demo device",
    registrationNumber: partial.actor.registrationNumber,
    actorId: partial.actor.id,
    actorName: partial.actor.name,
    actorRole: partial.actor.role === "system" ? "system" : `${partial.actor.role}:${partial.actor.subrole}`,
    facilityId: partial.actor.facilityId,
    facilityName: partial.actor.facilityName,
    referralId: partial.referralId,
    type: partial.type,
    previousStatus: partial.previousStatus,
    newStatus: partial.newStatus,
    deviceTime: partial.deviceTime,
    serverTime: partial.serverTime,
    reason: partial.reason,
    meta: partial.meta,
  };
}

function vital(referralActor: ActorStamp, when: string, values: Omit<Vital, "id" | "deviceTime" | "serverTime" | "recordedBy">): Vital {
  return {
    id: `vit_${crypto.randomUUID()}`,
    ...values,
    deviceTime: when,
    serverTime: when,
    recordedBy: referralActor,
  };
}

